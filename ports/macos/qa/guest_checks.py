#!/usr/bin/env python3
"""Collect bounded guest evidence from the running task-owned macOS QA AVD."""
from __future__ import annotations

import argparse
from collections import Counter
from contextlib import contextmanager
import datetime as dt
import hashlib
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
import importlib.util
import json
from pathlib import Path
import re
import subprocess
import sys
import threading
import uuid

SOURCE = Path(__file__).resolve().parents[1] / "runtime/runtime.py"
SPEC = importlib.util.spec_from_file_location("modavd_guest_runtime", SOURCE)
runtime_module = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(runtime_module)
Runtime = runtime_module.Runtime
PAYLOAD = b"ModAVD guest QA fixed payload v1\n" * 1024
PAYLOAD_SHA256 = hashlib.sha256(PAYLOAD).hexdigest()
MAX_EVIDENCE = 128 * 1024


def evidence(text: str) -> dict:
    raw = text.encode("utf-8", errors="replace")
    return {"text": raw[:MAX_EVIDENCE].decode("utf-8", errors="replace"),
            "bytes": len(raw), "sha256": hashlib.sha256(raw).hexdigest(),
            "truncated": len(raw) > MAX_EVIDENCE}


def result(status: str, detail: str, output: str = "", **extra) -> dict:
    return {"status": status, "detail": detail, "evidence": evidence(output), **extra}


@contextmanager
def payload_server(token: str):
    """Serve only self-generated bytes on a random loopback port; no files served."""
    if not re.fullmatch(r"[a-f0-9]{32}", token):
        raise ValueError("invalid QA token")
    path = f"/modavd-qa-{token}/payload"

    class Handler(BaseHTTPRequestHandler):
        def do_GET(self):
            if self.path != path:
                self.send_error(404)
                return
            self.send_response(200)
            self.send_header("Content-Type", "application/octet-stream")
            self.send_header("Content-Length", str(len(PAYLOAD)))
            self.send_header("Connection", "close")
            self.end_headers()
            self.wfile.write(PAYLOAD)

        def log_message(self, *_):
            pass

    server = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
    server.daemon_threads = True
    thread = threading.Thread(target=server.serve_forever, kwargs={"poll_interval": 0.1}, daemon=True)
    thread.start()
    try:
        yield server.server_address[1], path
    finally:
        server.shutdown()
        server.server_close()
        thread.join(timeout=2)


class GuestChecks:
    def __init__(self, instance: Runtime, timeout: int = 20):
        self.runtime = instance
        self.timeout = timeout
        self.identity = None

    def owned(self) -> str:
        """Check both recorded PIDs before Runtime can issue any ADB request.

        Runtime.adb may start an absent server, so a missing/stale private server
        is rejected here. Every subsequent operation repeats the process checks
        and Runtime.owned_device's guest AVD-name check.
        """
        root = self.runtime.root
        marker = json.loads((root / "runtime.json").read_text())
        if marker.get("schemaVersion") != 1 or not re.fullmatch(r"[a-f0-9]{32}", marker.get("id", "")):
            raise RuntimeError("runtime.json is not an owned QA runtime")
        server = json.loads((root / "adb-server.json").read_text())
        emulator = json.loads((root / "emulator.json").read_text())
        name = "modavd_macos_qa_" + marker["id"][:8]
        for record, tag in [(server, "server nodaemon"),
                            (server, f"tcp:{runtime_module.ADB_PORT}"),
                            (server, str(root / "sdk/platform-tools/adb")),
                            (emulator, name)]:
            if not runtime_module.same_process(record, tag):
                raise RuntimeError("recorded private ADB/emulator PID is missing, stale or foreign; no ADB request sent")
        snapshot = (server["pid"], server["started"], emulator["pid"], emulator["started"], marker["id"])
        if self.identity is not None and snapshot != self.identity:
            raise RuntimeError("task process identity changed during collection; no further guest access")
        serial = self.runtime.owned_device()
        if serial != f"emulator-{runtime_module.CONSOLE_PORT}":
            raise RuntimeError("unexpected task serial")
        self.identity = snapshot
        return serial

    def shell(self, script: str) -> str:
        serial = self.owned()
        completed = self.runtime.adb("-s", serial, "shell", script, timeout=self.timeout)
        # Compound diagnostics may succeed overall while an earlier read fails.
        # Keep stderr so permission errors cannot disappear behind a later
        # successful command, such as a readable virtio driver symlink.
        return (completed.stdout or "") + (completed.stderr or "")

    def read(self, script: str, detail: str) -> dict:
        try:
            output = self.shell(script)
            if not output.strip():
                return result("unavailable", "command returned no evidence: " + detail)
            if re.search(r"Permission (?:denied|Denial)|not found|Can't find service|Unknown command|unknown command", output):
                return result("unavailable", detail + ": command/service/permission unavailable", output)
            return result("observed", detail, output)
        except subprocess.CalledProcessError as error:
            return result("unavailable", detail + ": command failed; this alone is not a feature failure",
                          (error.stdout or "") + (error.stderr or ""), returncode=error.returncode)
        except (OSError, RuntimeError, subprocess.TimeoutExpired, ValueError, KeyError) as error:
            return result("unavailable", detail + ": " + str(error))

    def network(self) -> dict:
        token = uuid.uuid4().hex
        directory = f"/data/local/tmp/modavd-qa-{token}"
        created = False
        record = result("unavailable", "network check did not run")
        try:
            # Some toybox help goes to stderr and exits nonzero. Check applets
            # directly rather than treating a missing applet as broken networking.
            applets = self.shell("toybox")
            if not all(re.search(r"(?:^|\s)" + name + r"(?:\s|$)", applets) for name in ("nc", "sha256sum", "tail")):
                return result("unsupported", "required toybox applets unavailable", applets)
            runtime_module.space(self.runtime.root, len(PAYLOAD) * 4 + 16384)
            self.shell(f"umask 077; mkdir {directory} && printf '%s' '{token}' > {directory}/owner")
            created = True
            with payload_server(token) as (port, request_path):
                script = (f"printf 'GET {request_path} HTTP/1.0\\r\\nHost: 10.0.2.2\\r\\nConnection: close\\r\\n\\r\\n' > {directory}/request.http\n"
                          f"toybox nc -w {min(self.timeout, 15)} 10.0.2.2 {port} < {directory}/request.http > {directory}/response.http || exit $?\n"
                          f"toybox head -n 1 {directory}/response.http\n"
                          f"toybox tail -c {len(PAYLOAD)} {directory}/response.http > {directory}/payload.bin || exit $?\n"
                          f"toybox sha256sum {directory}/payload.bin\n"
                          f"toybox wc -c < {directory}/payload.bin")
                output = self.shell(script)
                match = re.search(r"(?m)^([a-fA-F0-9]{64})\s+", output)
                received = match.group(1).lower() if match else None
                ok = bool(re.search(r"HTTP/1\.[01] 200(?:\s|$)", output)) and received == PAYLOAD_SHA256
                record = result("pass" if ok else "fail", "small guest-to-host loopback HTTP transfer SHA-256 comparison",
                                output, expectedSha256=PAYLOAD_SHA256, receivedSha256=received,
                                payloadBytes=len(PAYLOAD), hostBind="127.0.0.1", guestHost="10.0.2.2")
        except subprocess.CalledProcessError as error:
            record = result("unavailable", "network command did not complete; inspect evidence before diagnosing networking",
                            (error.stdout or "") + (error.stderr or ""), returncode=error.returncode)
        except (OSError, RuntimeError, subprocess.TimeoutExpired, ValueError, KeyError) as error:
            record = result("unavailable", str(error))
        finally:
            if created:
                try:
                    # No recursive deletion: unexpected files are left for review.
                    self.shell(f"test \"$(cat {directory}/owner)\" = '{token}' && "
                               f"rm -- {directory}/request.http {directory}/response.http {directory}/payload.bin {directory}/owner; "
                               f"rmdir {directory}")
                    record["cleanup"] = "completed"
                except (OSError, RuntimeError, subprocess.SubprocessError, ValueError, KeyError) as error:
                    record["cleanup"] = "unavailable"
                    record["cleanupDetail"] = str(error)
                    record["guestPath"] = directory
        return record

    def collect(self, network: bool = False) -> dict:
        runtime_module.space(self.runtime.root, 2 * 1024**2)
        self.owned()
        report = {"schema": 1, "collectedAt": dt.datetime.now(dt.timezone.utc).isoformat(),
                  "root": str(self.runtime.root), "serial": f"emulator-{runtime_module.CONSOLE_PORT}",
                  "adbServerPort": runtime_module.ADB_PORT,
                  "processIdentity": self.identity, "checks": {}}
        checks = report["checks"]
        checks["identity"] = self.read("getprop ro.product.cpu.abi; getprop ro.product.cpu.abilist; getprop ro.build.version.sdk; getprop sys.boot_completed", "ABI/API/boot properties")
        if checks["identity"]["status"] == "observed":
            lines = checks["identity"]["evidence"]["text"].splitlines()
            if len(lines) == 4:
                checks["identity"]["observed"] = dict(zip(("abi", "abiList", "api", "bootCompleted"), lines))
                checks["identity"]["status"] = "pass" if lines[0] == "arm64-v8a" and lines[2] == "34" and lines[3] == "1" else "fail"
            else:
                checks["identity"]["status"] = "unavailable"
        commands = {
            "gles": ("dumpsys SurfaceFlinger | grep -E 'GLES:|GL_VENDOR|GL_RENDERER|GL_VERSION'", "SurfaceFlinger GLES renderer/version evidence"),
            "vulkan_features": ("pm list features", "Android-advertised Vulkan features"),
            "vulkan_probe": ("cmd gpu vkjson", "guest Vulkan enumeration; enumeration does not validate game rendering"),
            "cpu": ("cat /sys/devices/system/cpu/online; cat /proc/cpuinfo", "online CPU set and CPU information"),
            "memory": ("cat /proc/meminfo; grep -E '^(pgfree|balloon_|nr_free_pages)' /proc/vmstat", "guest memory and VM counters; no reclamation load applied"),
            "disk": ("df -k /data /data/local/tmp; cat /proc/mounts | grep ' /data '", "guest data filesystem capacity and mount evidence"),
            "kernel": ("uname -a; cat /proc/version", "guest kernel identity"),
            "virtio": ("for d in /sys/bus/virtio/devices/*; do [ -d \"$d\" ] || continue; printf '\\n%s\\n' \"$d\"; cat \"$d/device\" \"$d/features\"; readlink \"$d/driver\"; done", "virtio device IDs, raw negotiated features, and bound drivers"),
            "page_reporting": ("if [ -r /proc/config.gz ]; then zcat /proc/config.gz | grep -E '^(CONFIG_(VIRTIO_BALLOON|PAGE_REPORTING)=|# CONFIG_(VIRTIO_BALLOON|PAGE_REPORTING) is not set)'; fi; if [ -r /sys/module/page_reporting/parameters/order ]; then printf 'page_reporting order='; cat /sys/module/page_reporting/parameters/order; fi", "kernel page-reporting capability evidence; not proof of physical host memory return"),
        }
        for name, (script, description) in commands.items():
            checks[name] = self.read(script, description)
        features = checks["vulkan_features"]
        if features["status"] == "observed" and "feature:" in features["evidence"]["text"] and "vulkan" not in features["evidence"]["text"].lower():
            features["status"] = "unsupported"
        reporting = checks["page_reporting"]
        if "# CONFIG_PAGE_REPORTING is not set" in reporting["evidence"]["text"]:
            reporting["status"] = "unsupported"
        probe = checks["vulkan_probe"]
        if probe["status"] == "observed":
            try:
                data = json.loads(probe["evidence"]["text"])
                if isinstance(data, dict) and isinstance(data.get("devices"), list):
                    probe["deviceCount"] = len(data["devices"])
                    probe["status"] = "pass" if data["devices"] else "unsupported"
            except json.JSONDecodeError:
                pass
        checks["network"] = self.network() if network else result("not_run", "enable --network for the fixed small loopback transfer")
        report["statusCounts"] = dict(Counter(item["status"] for item in checks.values()))
        report["overall"] = ("contains_failures" if report["statusCounts"].get("fail") else
                             "incomplete_evidence" if report["statusCounts"].get("unavailable") else
                             "evidence_collected")
        return report


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=runtime_module.REPO / ".macos-work/runtime")
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("plan", help="Print the scope; no runtime initialization, ADB or guest access")
    run = commands.add_parser("run", help="Only after the task-owned emulator and private ADB server are boot-ready")
    run.add_argument("--network", action="store_true", help="Transfer fixed self-generated bytes from a temporary host loopback service")
    run.add_argument("--timeout", type=int, choices=range(5, 61), default=20)
    run.add_argument("--output", type=Path, help="New JSON evidence file; existing files are never overwritten")
    args = parser.parse_args(argv)
    if args.command == "plan":
        print(json.dumps({"mode": "plan", "root": str(args.root.expanduser().resolve()),
                          "adbServerPort": runtime_module.ADB_PORT, "serial": f"emulator-{runtime_module.CONSOLE_PORT}",
                          "guestWrites": "/data/local/tmp/modavd-qa-<random-token> only with --network",
                          "checks": ["ABI/API/boot", "GLES", "Vulkan", "CPU", "memory", "disk", "kernel/virtio/page-reporting"],
                          "networkPayloadBytes": len(PAYLOAD), "networkPayloadSha256": PAYLOAD_SHA256}, indent=2))
        return 0
    report = GuestChecks(Runtime(args.root), args.timeout).collect(args.network)
    output = args.output or args.root / "logs" / ("guest-checks-" + uuid.uuid4().hex + ".json")
    # Require an existing parent: run never initializes or adopts a foreign root.
    with output.open("x") as target:
        json.dump(report, target, ensure_ascii=False, indent=2)
        target.write("\n")
    print(json.dumps({"report": str(output.resolve()), "overall": report["overall"], "statusCounts": report["statusCounts"]}, indent=2))
    return 1 if report["statusCounts"].get("fail") else 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (OSError, RuntimeError, ValueError, KeyError, subprocess.SubprocessError) as error:
        print(f"Guest checks unavailable: {error}", file=sys.stderr)
        sys.exit(2)
